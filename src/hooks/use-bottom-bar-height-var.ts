"use client"

import { useLayoutEffect, type RefObject } from "react"

// Тот же приём, что и у --site-header-h (см. use-header-height-var.ts):
// TourBottomBar — fixed поверх колоды, из потока не вычитается сама, из-за
// чего последние строчки высоких слайдов (например "Что взять с собой" на
// турах с длинным списком) уезжали под неё (Виктор со скриншотом: "кнопка
// внизу перекрывает последние строчки"). ResizeObserver держит реальную
// высоту плашки в --tour-bottom-bar-h.
//
// Раньше эта переменная ещё и вычиталась из высоты САМОЙ деки (общей для
// всех слайдов Swiper) — из-за чего на слайдах, где плашка скрыта (фото,
// бронь), деке физически не хватало места, хотя перекрывать там нечего
// (Виктор: "убери зарезервированный блок, сделай весь экран доступным для
// контента"). Убрали ту вычитку совсем: высота деки теперь ВСЕГДА
// одинаковая (100dvh - хедер, без вычитания плашки — см. tour-page-
// client.tsx), Swiper никогда не пересчитывает размеры слайдов при
// переключении. Резервирование места под ВИДИМУЮ плашку теперь делает
// каждый слайд сам себе, через padding-bottom с этой же переменной (см.
// tour-itinerary-slide.tsx и аналогичные) — тем слайдам, где плашка
// скрыта (фото, бронь), эта padding просто не добавлена.
//
// Раньше здесь была пляска с "reserve" (0 на скрытых слайдах, дальше
// swiper.update() на transitionEnd, потом ещё settledSlideIndex) — три
// фикса подряд так и не убрали видимое дёрганье/доскок размера при
// переключении (Виктор: то "резко", то "видно как пересчитывается").
// Корень был не в ТАЙМИНГЕ пересчёта, а в том, что высота деки вообще
// была общей на всех слайдах и требовала пересчёта. Раз высота деки
// теперь константа — пересчитывать (и тем более синхронизировать с
// Swiper) нечего, весь класс проблемы устранён структурно.
//
// useLayoutEffect, не useEffect — отрабатывает ДО любого обычного useEffect
// в дереве, так что другие компоненты, читающие эту CSS-переменную при
// монтировании, всегда видят уже актуальное значение, а не дефолт.
export function useBottomBarHeightVar(ref: RefObject<HTMLElement | null>) {
  useLayoutEffect(() => {
    const el = ref.current
    if (!el) return
    const update = () => {
      document.documentElement.style.setProperty("--tour-bottom-bar-h", `${el.getBoundingClientRect().height}px`)
    }
    update()
    const observer = new ResizeObserver(update)
    observer.observe(el)
    return () => observer.disconnect()
  }, [ref])
}
