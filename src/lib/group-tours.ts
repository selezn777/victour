export function findGroupProgram(slug: string | null | undefined): GroupProgram | undefined {
  return slug ? GROUP_PROGRAMS.find((p) => p.slug === slug) : undefined
}

/** Ищет программу по тексту из расписания («Острова», «с историком»...). */
export function matchGroupProgram(title: string): GroupProgram | undefined {
  const t = title.toLowerCase().replace(/ё/g, "е").trim()
  if (!t) return undefined
  return GROUP_PROGRAMS.find(
    (p) => p.title.toLowerCase().replace(/ё/g, "е") === t || p.aliases.some((a) => t === a || t.includes(a)),
  )
}
