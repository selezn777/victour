export function findGroupProgram(slug: string | null | undefined): GroupProgram | undefined {
  return slug ? GROUP_PROGRAMS.find((p) => p.slug === slug) : undefined
}

export function groupPriceLabel(p: Pick<GroupProgram, "priceUsd" | "priceFrom">): string {
  return p.priceUsd === null ? "по запросу" : `${p.priceFrom ? "от " : ""}$${p.priceUsd}`
}

const norm = (s: string) => s.toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ").trim()

/**
 * Ищет программу по тексту из расписания («Острова + канатка», «сафари»...).
 * Названия пересекаются («острова» есть в двух программах), поэтому побеждает самое длинное совпадение.
 */
export function matchGroupProgram(title: string): GroupProgram | undefined {
  const t = norm(title)
  if (!t) return undefined
  let best: { p: GroupProgram; len: number } | undefined
  for (const p of GROUP_PROGRAMS) {
    for (const a of [p.title, ...p.aliases].map(norm)) {
      if ((t === a || t.includes(a)) && (!best || a.length > best.len)) best = { p, len: a.length }
    }
  }
  return best?.p
}
