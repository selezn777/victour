const { data: ex } = await s.from("tours").select("id").eq("slug", SLUG).maybeSingle()
let id
if (ex) {
  const { error } = await s.from("tours").update(tour).eq("id", ex.id)
  if (error) throw error
  id = ex.id
  await s.from("pricing_tiers").delete().eq("tour_id", id)
} else {
  const { data, error } = await s.from("tours").insert(tour).select("id").single()
  if (error) throw error
  id = data.id
}

