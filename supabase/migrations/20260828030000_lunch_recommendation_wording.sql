-- Виктор: "везде напиши, что мы даём рекомендацию ресторана, вы заказываете
-- блюда по меню и сами их оплачиваете" — единая формулировка для всех
-- пунктов маршрута/excludes, где обед/ужин не входит в пакет, гости платят
-- сами. Плюс для "Обед в кафе с вертолётом" (Авторский Нячанг) — добавлена
-- рекомендация попробовать жареную змею, лучшее место в городе для этого.

update tours
set itinerary = jsonb_set(
  itinerary,
  '{7,description,ru}',
  '"Даём рекомендацию — здесь можно попробовать жареную змею, лучшее место в городе для этого. Блюда выбираете по меню и оплачиваете сами."'
)
where slug = 'nyachang-avtorskiy';

update tours
set excludes = '[{"ru": "Обед в кафе с вертолётом — рекомендация ресторана от нас, блюда по меню оплачиваете сами", "en": null}]'::jsonb
where slug = 'nyachang-avtorskiy';

update tours
set itinerary = jsonb_set(
  itinerary,
  '{7,description,ru}',
  '"Парк с лазерным шоу и ресторан по нашей рекомендации — блюда по меню оплачиваете сами."'
)
where slug = 'dalat-2-dnya';

update tours
set excludes = jsonb_set(
  excludes,
  '{0,ru}',
  '"Обеды и ужин — рекомендация и бронирование ресторана от нас, блюда по меню оплачиваете сами"'
)
where slug = 'dalat-2-dnya';
